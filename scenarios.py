def validate() -> list[str]:
    """
    Complain about anything malformed, before a long run rather than during.

    A "bodies" scenario is deliberately exempt from the empty check — an empty
    string is the whole point of a bad-input case, and refusing to run one
    would make that criterion untestable.
    """
    problems = []
    for i, scenario in enumerate(SCENARIOS, 1):
        if not scenario.get("name"):
            problems.append(f"scenario {i} has no name")

        kinds = [k for k in ("texts", "bodies", "appeals") if scenario.get(k)]
        if len(kinds) > 1:
            problems.append(
                f"scenario {i} ('{scenario.get('name')}') has {' and '.join(kinds)} "
                f"— pick one"
            )
            continue

        bodies = scenario.get("bodies")
        if bodies:
            for j, body in enumerate(bodies, 1):
                if not isinstance(body, (dict, list)):
                    problems.append(
                        f"scenario {i}, body {j} is not a dict or list — bodies are "
                        f"whole request bodies, like {{'text': '', 'creator_id': 'x'}}"
                    )
            continue

        appeals = scenario.get("appeals")
        if appeals:
            reasoning = appeals.get("reasoning")
            if not isinstance(reasoning, str) or not reasoning.strip():
                problems.append(f"scenario {i} ('{scenario['name']}') needs a reasoning")
            texts = appeals.get("texts") or []
            if not texts:
                problems.append(f"scenario {i} ('{scenario['name']}') has no texts to appeal")
        else:
            texts = scenario.get("texts")
            if not texts:
                problems.append(f"scenario {i} has no texts, bodies or appeals")
                continue

        for j, text in enumerate(texts, 1):
            if not str(text).strip():
                problems.append(
                    f"scenario {i}, text {j} is empty — if an empty submission is what "
                    f"you're testing, use 'bodies' instead of 'texts'"
                )
            elif str(text).startswith("REPLACE ME"):
                problems.append(
                    f"scenario {i} ('{scenario.get('name')}'), text {j} is still "
                    f"the placeholder"
                )
    return problems
