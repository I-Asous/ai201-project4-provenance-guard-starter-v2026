def score(text):
    """Exactly what /submit computes, minus the route and the log."""
    model = detector.model_signal(text)
    style = stylometry.style_signal(text)
    combined = scoring.combine_signals(model, style)
    return {
        "words": len(text.split()),
        "perplexity": round(detector.perplexity(text), 1),
        "model": model,
        "style": style,
        "gap": round(abs(model - style), 4),
        "combined": combined,
        "label": scoring.score_to_label(combined)[0],
    }


def table(rows):
    lines = ["| Input | Words | Perplexity | Model | Style | Gap | Combined | Label |",
             "|---|---|---|---|---|---|---|---|"]
    for name, s in rows:
        lines.append(f"| {name} | {s['words']} | {s['perplexity']} | {s['model']:.4f} | "
                     f"{s['style']:.4f} | {s['gap']:.4f} | {s['combined']:.4f} | {s['label']} |")
    return lines


def without_instruction(attack_id, text):
    """The AI part of a prompt-injection attack, with the instruction cut off."""
    if "\n\n" in text:                       # PI02, PI03: instruction, blank line, AI text
        return text.split("\n\n", 1)[1].strip()
    # PI01: three instruction sentences run straight into the AI text
    sentences = re.split(r"(?<=[.!?])\s+", text.strip())
    return " ".join(sentences[3:])


